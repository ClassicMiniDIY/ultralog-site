// Regenerates data/openecu/adapters.json from the OpenECU spec corpus in the UltraLog repo.
//
// This is a MANUAL step, deliberately not part of `build`. The generated JSON is committed,
// so the build reads no network and an ECU page's channel table cannot silently go missing.
// That is the opposite of scripts/sync-wiki.ts on purpose: the wiki is prose that changes
// often and whose absence is visible, whereas a missing adapter empties a structured table
// in a way nobody notices. The site used to fetch this from oecua.org at build time, which
// is exactly the failure mode being removed — see CLAUDE.md, "ECU pages".
//
// Run it when UltraLog's corpus changes:
//
//   bun scripts/sync-adapters.ts                       # from ClassicMiniDIY/UltraLog main
//   bun scripts/sync-adapters.ts --ref v3.2.0          # from a tag
//   bun scripts/sync-adapters.ts --from ../UltraLog     # from a local checkout
//
// Then commit the result. The output records the source ref and each file's sha256 so a
// later run can tell whether anything actually moved.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { join } from 'node:path'
import { parse } from 'yaml'
import { ECUS } from '../shared/utils/ecus'

const OUT = 'data/openecu/adapters.json'
const REPO = 'ClassicMiniDIY/UltraLog'
const CORPUS = 'spec/openecu/adapters'

interface RawChannel {
  id: string
  name: string
  category?: string
  unit?: string | null
  source_names?: string[]
}

interface RawAdapter {
  id: string
  name: string
  version: string
  vendor: string
  channels: RawChannel[]
}

/** What an ECU page renders. Everything else in the spec is dropped. */
interface TrimmedAdapter {
  id: string
  name: string
  version: string
  vendor: string
  channels: { name: string; unit: string | null; category: string; sourceNames: string[] }[]
}

function arg(flag: string): string | undefined {
  const i = process.argv.indexOf(flag)
  return i === -1 ? undefined : process.argv[i + 1]
}

const localRepo = arg('--from')
const ref = arg('--ref') ?? 'main'

/** The adapter refs the site actually needs, straight from the ECU list. */
const refs = [...new Set(ECUS.map((e) => e.oecua).filter((r): r is string => !!r))].sort()

async function read(ref_: string): Promise<string> {
  const rel = `${CORPUS}/${ref_}.adapter.yaml`
  if (localRepo) return readFileSync(join(localRepo, rel), 'utf8')
  const url = `https://raw.githubusercontent.com/${REPO}/${ref}/${rel}`
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`)
  return res.text()
}

const unitOf = (u: unknown) => (typeof u === 'string' && u.trim() !== '' ? u.trim() : null)

const adapters: Record<string, TrimmedAdapter> = {}
const digests: Record<string, string> = {}

for (const r of refs) {
  const text = await read(r)
  digests[r] = createHash('sha256').update(text).digest('hex').slice(0, 16)
  const raw = parse(text) as RawAdapter

  const channels = (raw.channels ?? []).map((c) => ({
    name: c.name,
    unit: unitOf(c.unit),
    category: c.category ?? 'other',
    // The spec is snake_case. The old oecua.org JSON API served these camelCased, which is
    // why this mapping exists at all — read straight from YAML, `sourceNames` is undefined
    // and every channel silently loses its source names.
    sourceNames: c.source_names ?? [],
  }))

  if (channels.length === 0) throw new Error(`${r} parsed to zero channels`)
  adapters[r] = { id: raw.id, name: raw.name, version: raw.version, vendor: raw.vendor, channels }
  console.log(`[adapters] ${r}: ${channels.length} channels`)
}

const payload = {
  $comment: `Generated by scripts/sync-adapters.ts from ${REPO}. Do not hand-edit.`,
  source: { repo: REPO, ref, corpus: CORPUS, generated: new Date().toISOString().slice(0, 10) },
  digests,
  adapters,
}

mkdirSync('data/openecu', { recursive: true })
writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`)

const total = Object.values(adapters).reduce((n, a) => n + a.channels.length, 0)
console.log(`[adapters] wrote ${OUT}: ${refs.length} adapters, ${total} channels`)
